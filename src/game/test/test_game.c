void test_game_update(void) {
    s64 selected;
    s64 selected_2;

    input_get_p1_pressed();
    if (reg_d0.w & 1) {
        g_test_redraw = 1;
        sfx_cursor_move();
        test_game_cursor_erase();
        g_test_cursor -= 1;
        if (0 > g_test_cursor) {
            g_test_cursor = 4;
        }
        test_game_cursor_draw();
    }
    input_get_p1_pressed();
    if (reg_d0.w & 2) {
        g_test_redraw = 1;
        sfx_cursor_move();
        test_game_cursor_erase();
        g_test_cursor += 1;
        if (g_test_cursor > 4) {
            g_test_cursor = 0;
        }
        test_game_cursor_draw();
    }
    input_get_p1_pressed();
    if (reg_d0.w & 4) {
        g_test_redraw = 1;
        if (g_test_cursor != 4) {
            sfx_cursor_move();
        }
        if (g_test_cursor == 0) {
            g_setting_difficulty -= 1;
            if (0 > (s8) g_setting_difficulty) {
                g_setting_difficulty = 3;
            }
        }
        selected = g_test_cursor;
        if (selected == 1) {
            g_setting_extend -= 1;
            if (0 > (s8) g_setting_extend) {
                g_setting_extend = 3;
            }
        }
        if (selected == 2) {
            g_setting_ship_stock -= 1;
            if (0 > (s8) g_setting_ship_stock) {
                g_setting_ship_stock = 4;
            }
        }
        if (selected == 3) {
            g_setting_rapid_fire -= 1;
            g_setting_rapid_fire &= 1;
        }
    }
    input_get_p1_pressed();
    if (reg_d0.w & 8) {
        g_test_redraw = 1;
        if (g_test_cursor != 4) {
            sfx_cursor_move();
        }
        if (g_test_cursor == 0) {
            g_setting_difficulty += 1;
            if ((s8) g_setting_difficulty >= 4) {
                g_setting_difficulty = 0;
            }
        }
        selected_2 = g_test_cursor;
        if (selected_2 == 1) {
            g_setting_extend += 1;
            if ((s8) g_setting_extend >= 4) {
                g_setting_extend = 0;
            }
        }
        if (selected_2 == 2) {
            g_setting_ship_stock += 1;
            if ((s8) g_setting_ship_stock >= 5) {
                g_setting_ship_stock = 0;
            }
        }
        if (selected_2 == 3) {
            g_setting_rapid_fire += 1;
            g_setting_rapid_fire &= 1;
        }
    }
    input_get_p1_pressed();
    if ((reg_d0.w & 0x10) && (g_test_cursor == 4)) {
        sfx_confirm();
        reg_d0.w = 0;
        test_screen_request();
    } else if (g_test_redraw != 0) {
        g_test_redraw = 0;
        test_game_print_items();
        test_game_print_values();
    }
    reg_d0.w = 0;
}

