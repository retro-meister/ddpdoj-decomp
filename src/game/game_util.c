void binary_to_bcd(void) {
    s8 buf[4];
    u8 *a0;
    u32 s0;
    u32 s1;
    u32 s3;
    u32 s4;
    s32 i;
    s32 off;
    s64 t;
    s64 x;

    s0 = reg_d0.w;
    s1 = reg_d1.w;
    s3 = reg_d3.w;
    s4 = reg_d4.w;
    a0 = reg_a0;
    reg_d2.w = 0;
    off = 0;
    for (i = 0; i < 4; i++) {
        x = (s32) reg_d0.h[0];
        t = *(s64 *)((u8 *)((s64 *)decimal_place_values) + off);
        if (x >= t) {
#ifdef DDPDOJ_PC
            buf[i] = x / t;
            reg_d0.h[0] = x % t;
#else
            buf[i] = __divdi3(x, t);
            reg_d0.h[0] = __moddi3(x, t);
#endif
        } else {
            buf[i] = 0;
        }
        reg_d2.w |= buf[i];
        reg_d2.w <<= 4;
        off += 8;
    }
    reg_d2.w |= reg_d0.h[0];
    reg_d1.w = s1;
    reg_d3.w = s3;
    reg_d4.w = s4;
    reg_a0 = a0;
    reg_d0.w = s0;
}

void bcd_to_binary(void)
{
    unsigned char low = reg_d0.b[0];
    unsigned char high = reg_d0.b[1];

    reg_d2.w = 0;
    reg_tmp.b[0] = low & 15;
    reg_tmp.b[1] = low >> 4;
    reg_tmp.b[2] = high & 15;
    reg_tmp.b[3] = high >> 4;
    reg_d2.h[0] = reg_tmp.b[0] + (reg_tmp.b[1] * 10 +
        (reg_tmp.b[3] * 1000 + reg_tmp.b[2] * 100));
}

